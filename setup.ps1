# One-command setup for Windows: creates docker\.env with random secrets (first run only), starts Trace, waits until
# it is ready. Usage: .\setup.ps1   (add -NoStart to only write docker\.env)
param([switch]$NoStart)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot
$envFile = if ($env:TRACE_ENV_FILE) { $env:TRACE_ENV_FILE } else { 'docker\.env' }

# Letters and digits only: the database password goes into a URL, where / + = would break it.
function New-Secret {
  $chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
  $bytes = New-Object byte[] 48
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

if (Test-Path $envFile) {
  Write-Host "Using existing $envFile"
} else {
  $content = @(
    '# Generated by setup.ps1. Keep this file private; see docker\.env.example for more settings.'
    "POSTGRES_PASSWORD=$(New-Secret)"
    "TOKEN_SECRET=$(New-Secret)"
    "AUTH_SECRET=$(New-Secret)"
  ) -join "`n"
  $fullPath = if ([System.IO.Path]::IsPathRooted($envFile)) { $envFile } else { Join-Path (Get-Location) $envFile }
  [System.IO.File]::WriteAllText($fullPath, "$content`n", (New-Object System.Text.UTF8Encoding $false))
  Write-Host "Created $envFile with new random secrets"
}

if ($NoStart) { exit 0 }

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Write-Error 'Docker is required: https://docs.docker.com/get-docker/'
}

Write-Host 'Starting Trace (the first build takes a few minutes)...'
docker compose -f docker/compose.yml --env-file $envFile up --build -d
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$settings = Get-Content $envFile
$port = ($settings | Where-Object { $_ -match '^SERVER_PORT=(\d+)' } | ForEach-Object { $Matches[1] } | Select-Object -First 1)
if (-not $port) { $port = '8080' }
$dash = ($settings | Where-Object { $_ -match '^DASHBOARD_PORT=(\d+)' } | ForEach-Object { $Matches[1] } | Select-Object -First 1)
if (-not $dash) { $dash = '3000' }

Write-Host -NoNewline 'Waiting for the server'
for ($i = 0; $i -lt 120; $i++) {
  try {
    if ((Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "http://localhost:$port/health/ready").StatusCode -eq 200) { break }
  } catch { }
  Write-Host -NoNewline '.'
  Start-Sleep -Seconds 5
}
Write-Host ''
try { Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "http://localhost:$port/health/ready" | Out-Null } catch {
  Write-Error 'The server did not become ready. Logs: docker compose -f docker/compose.yml logs server'
}
Write-Host ''
Write-Host 'Trace is running.'
Write-Host "  Dashboard: http://localhost:$dash   (create the first account, then a project and keys)"
Write-Host "  API:       http://localhost:$port"
Write-Host '  Stop:      docker compose -f docker/compose.yml down'
