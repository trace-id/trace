#!/usr/bin/env sh
# One-command setup: creates docker/.env with random secrets (first run only), starts Trace, waits until it is ready.
# Usage: ./setup.sh            (add --no-start to only write docker/.env)
set -eu

cd "$(dirname "$0")"
ENV_FILE="${TRACE_ENV_FILE:-docker/.env}"

# Letters and digits only: the database password goes into a URL, where / + = would break it.
secret() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 48; }

if [ -f "$ENV_FILE" ]; then
  echo "Using existing $ENV_FILE"
else
  {
    echo "# Generated by setup.sh. Keep this file private; see docker/.env.example for more settings."
    echo "POSTGRES_PASSWORD=$(secret)"
    echo "TOKEN_SECRET=$(secret)"
    echo "AUTH_SECRET=$(secret)"
  } >"$ENV_FILE"
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  echo "Created $ENV_FILE with new random secrets"
fi

[ "${1:-}" = "--no-start" ] && exit 0

if ! command -v docker >/dev/null 2>&1; then
  echo "Docker is required: https://docs.docker.com/get-docker/" >&2
  exit 1
fi

echo "Starting Trace (the first build takes a few minutes)..."
docker compose -f docker/compose.yml --env-file "$ENV_FILE" up --build -d

PORT=$(sed -n 's/^SERVER_PORT=//p' "$ENV_FILE" | head -n 1)
PORT="${PORT:-8080}"
DASH=$(sed -n 's/^DASHBOARD_PORT=//p' "$ENV_FILE" | head -n 1)
DASH="${DASH:-3000}"
printf 'Waiting for the server'
i=0
until curl -fs "http://localhost:$PORT/health/ready" >/dev/null 2>&1; do
  i=$((i + 1))
  if [ "$i" -gt 120 ]; then
    echo
    echo "The server did not become ready. Logs: docker compose -f docker/compose.yml logs server" >&2
    exit 1
  fi
  printf '.'
  sleep 5
done
echo
echo
echo "Trace is running."
echo "  Dashboard: http://localhost:$DASH   (create the first account, then a project and keys)"
echo "  API:       http://localhost:$PORT"
echo "  Stop:      docker compose -f docker/compose.yml down"
